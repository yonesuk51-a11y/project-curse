function locate(source, id) {
  const start = source.indexOf(`<article class="record-detail" data-record="${id}"`);
  const end = start < 0 ? -1 : source.indexOf('</article>', start);
  if (start < 0 || end < 0) return null;
  return [start, end + '</article>'.length];
}

function apply(file) {
  let source = readFileSync(ROOT + file, 'utf8');
  const report = [];
  for (const [id, pairs] of Object.entries(EDITIONS)) {
    const range = locate(source, id);
    if (!range) throw new Error(`${file}: ${id} 기록을 찾지 못했다`);
    let block = source.slice(range[0], range[1]);
    let applied = 0;
    let already = 0;
    for (const [from, to] of pairs) {
      if (from === to) continue;
      const hits = block.split(from).length - 1;
      if (hits === 0 && block.includes(to)) { already += 1; continue; }
      if (hits !== 1) throw new Error(`${file}: ${id}에서 원문 문장이 ${hits}번 나온다 — ${from.slice(0, 40)}`);
      block = block.replace(from, () => to);
      applied += 1;
    }
    source = source.slice(0, range[0]) + block + source.slice(range[1]);
    report.push(`${id}: ${applied}개 적용${already ? `, ${already}개 이미 적용됨` : ''}`);
  }
  writeFileSync(ROOT + file, source);
  console.log(`${file} — ${report.join(' / ')}`);
}

const targets = process.argv.slice(2);
if (targets.length) targets.forEach(apply);
