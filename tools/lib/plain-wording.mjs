const ORIGINAL = new Map([...PLAIN_WORDING_1122].map(([before, after]) => [after, before]));

// 옛 원문 값(문자열·배열·객체)에 승인된 새 문장을 적용한다.
export function plainWording(value) {
  if (typeof value === 'string') return PLAIN_WORDING_1122.get(value) ?? value;
  if (Array.isArray(value)) return value.map(plainWording);
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, plainWording(item)]));
  return value;
}

// 새 문장이면 승인 전 옛 문장을 돌려준다. 옛 원문에 그 문장이 있었는지 확인할 때 쓴다.
export function plainOriginal(text) {
  return ORIGINAL.get(text) ?? text;
}
