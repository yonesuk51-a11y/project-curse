const escape = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

export function applyCanonRenames(text) {
  let out = String(text);
  for (const [from, to, table] of CANON_RENAMES) {
    if (!table) {
      out = out.split(from).join(to);
      continue;
    }
    const re = new RegExp(escape(from) + '(' + table.map(([a]) => a).join('|') + ')?', 'g');
    out = out.replace(re, (_whole, particle) => to + (particle ? table.find(([a]) => a === particle)[1] : ''));
  }
  return out.replace(/(?<!타)종 장부/g, '타종 장부').replace(/무등화/g, '불빛 없는');
}

// JSON으로 옮길 수 있는 값(배열·객체·문자열)에 표를 적용한다
export const renamedValue = (value) => JSON.parse(applyCanonRenames(JSON.stringify(value)));
