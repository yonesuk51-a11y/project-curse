import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';

const toolDir=path.dirname(fileURLToPath(import.meta.url));
const v6Dir=path.resolve(toolDir,'..');
const repoDir=path.resolve(v6Dir,'..');
const profilePath=path.join(repoDir,'assets','js','data','personnel-profile-data.js');
const registerPath=path.join(repoDir,'assets','js','data','personnel-data.js');
const targetPath=path.join(v6Dir,'assets','js','people-data.js');

const context={window:{}};
vm.createContext(context);
vm.runInContext(fs.readFileSync(profilePath,'utf8'),context,{filename:profilePath});
vm.runInContext(fs.readFileSync(registerPath,'utf8'),context,{filename:registerPath});

const source=context.window.ProjectCursePersonnel;
if(!source||source.records.length!==56) throw new Error('Expected the protected 56-record personnel intake source.');

const metadata={
  version:'6.0.0-alpha.4',
  schema:'project-curse-v6-personnel-intake-v1',
  migrationState:'LEGACY INTAKE / NOT V6 CANON',
  snapshotOf:source.version,
  recordCount:source.records.length,
  generatedFrom:['assets/js/data/personnel-data.js','assets/js/data/personnel-profile-data.js','PERSONNEL_SOURCE_NOTES.md'],
  boundary:'원 명부 정보와 잠정 신원 보완을 표시하되, 2006년 활동 표기를 2042년 생존 판정으로 승격하지 않는다.',
  protagonistRule:'프레이를 자동 중심 인물로 복구하지 않으며 모든 사건 연결은 별도 V6 채택 판정을 요구한다.'
};

const records=source.records.map(record=>({
  ...record,
  v6Adoption:'UNREVIEWED',
  v6IncidentLinks:[],
  current2042:'UNRESOLVED'
}));

const payload=`// Generated by v6/tools/build-people-snapshot.mjs. Do not hand-edit the legacy intake payload.\n`+
  `const deepFreeze=value=>{if(!value||typeof value!=='object'||Object.isFrozen(value)) return value;Object.values(value).forEach(deepFreeze);return Object.freeze(value);};\n\n`+
  `export const PEOPLE_SOURCE=deepFreeze(${JSON.stringify(metadata,null,2)});\n\n`+
  `export const PEOPLE_GROUPS=deepFreeze(${JSON.stringify(source.groups,null,2)});\n\n`+
  `export const PEOPLE_STATUSES=deepFreeze(${JSON.stringify(source.statuses,null,2)});\n\n`+
  `export const PEOPLE_CERTAINTIES=deepFreeze(${JSON.stringify(source.certainties,null,2)});\n\n`+
  `export const PEOPLE_RECORDS=deepFreeze(${JSON.stringify(records,null,2)});\n`;

if(process.argv.includes('--check')){
  const current=fs.existsSync(targetPath)?fs.readFileSync(targetPath,'utf8'):'';
  if(current!==payload){
    console.error('V6 personnel snapshot is stale. Run node v6/tools/build-people-snapshot.mjs');
    process.exitCode=1;
  }else{
    console.log(`V6 personnel snapshot current: ${records.length} records`);
  }
}else{
  fs.writeFileSync(targetPath,payload,'utf8');
  console.log(`Wrote ${path.relative(repoDir,targetPath)} with ${records.length} records.`);
}
